    def identify_bando(self, documents: list[BandoDocumentClassification]) -> BandoIdentityProposal:
        primary = _primary(documents)
        text = primary.text if primary else ""
        title = _extract_title(text) or (primary.title if primary else "")
        issuer = _extract_issuer(text)
        edition = _extract_edition(text)
        publication_date = _extract_publication_date(text)
        deadline = _extract_deadline(text)
        territory = _extract_territory(text)
        missing = [name for name, value in {"title": title, "issuer": issuer, "edition": edition}.items() if not value]
        bando_id = _slug(" ".join(x for x in (issuer, title, edition) if x)) if not missing else ""
        status = "identity_incomplete" if missing else "draft"
        confidence = 1.0 - (len(missing) * 0.3)
        return BandoIdentityProposal(bando_id, title, issuer, edition, "1.0.0", publication_date, deadline, territory, status, confidence, missing)

    def identify_version(self, identity: BandoIdentityProposal, documents: list[BandoDocumentClassification]) -> str:
        if any(doc.source_type == "official_amendment" for doc in documents):
            return "1.0.1"
        return identity.version

