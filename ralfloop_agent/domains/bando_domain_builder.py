    def extract_calculations(self, identity: BandoIdentityProposal, documents: list[BandoDocumentClassification]) -> BandoCalculationExtraction:
        primary = _primary(documents)
        if not primary or primary.binding_level != "binding_official":
            return BandoCalculationExtraction([])
        text = _space(primary.text)
        source = primary.source_id
        calculations = []
        ambiguous = []
        max_rate = _extract_max_rate(text)
        min_amount, max_amount = _extract_amount_range(text)
        if max_rate is not None:
            calculations.append({
                "calculation_id": "contribution_percentage",
                "description": "Maximum contribution percentage over total costs.",
                "formula": "total_costs * contribution_rate",
                "required_inputs": ["total_costs", "contribution_rate"],
                "units": {"total_costs": "EUR", "result": "EUR"},
                "source_refs": [source],
                "source_pages": [_page_of(primary.text, "contributo")],
                "minimum": min_amount,
                "maximum": max_amount,
                "cap": max_amount,
                "rounding_policy": "not_specified",
                "percentage": max_rate,
            })
        if max_rate is not None and not re.search(r"costi totali", text, re.I):
            ambiguous.append({"reason": "ambiguous_calculation_basis", "jury_required": True, "source_refs": [source]})
        return BandoCalculationExtraction(calculations, ambiguous)

    def extract_deadlines(self, documents: list[BandoDocumentClassification]) -> dict[str, Any]:
        primary = _primary(documents)
        return {"deadline": _extract_deadline(primary.text if primary else "")}

    def extract_required_documents(self, documents: list[BandoDocumentClassification]) -> list[str]:
        primary = _primary(documents)
        return _extract_required_documents(primary.text if primary else "")

    def extract_conflicts(self, documents: list[BandoDocumentClassification], rules: list[dict[str, Any]]) -> list[dict[str, Any]]:
        conflicts = []
        for doc in documents:
            if doc.source_type == "official_faq" and doc.binding_level == "binding_official":
                for rule in rules:
                    if rule.get("source_refs") and rule["source_refs"][0] != doc.source_id and rule.get("structured_effect", {}).get("value") in doc.text:
                        conflicts.append({
                            "conflict_id": f"faq_conflict:{rule['rule_id']}",
                            "rule_id": rule["rule_id"],
                            "source_refs": [rule["source_refs"][0], doc.source_id],
                            "description": "Potential FAQ conflict requires review.",
                            "blocking": True,
                            "status": "conflicting_official_documents",
                        })
        return conflicts

    def build_tests(self, identity: BandoIdentityProposal, rules: list[dict[str, Any]]) -> list[dict[str, Any]]:
        tests = []
        for rule in rules:
            field = rule.get("field") or rule.get("structured_effect", {}).get("field")
            if field in {"deadline", "territory", "contribution_max_rate", "contribution_max_amount"}:
                tests.append({
                    "test_id": f"{rule['rule_id']}_deterministic",
                    "kind": "deterministic",
                    "input": {"field": field},
                    "expected": {"value": rule.get("value") or rule.get("structured_effect", {}).get("value")},
                    "source_refs": rule.get("source_refs", []),
                })
        return tests

    def build_draft(self, request: BandoBuildRequest | dict[str, Any]) -> BandoBuildResult:
        req = _request_from_any(request)
        self.output_root = Path(req.output_root)
        docs = self.classify_documents(req)
        identity = self.identify_bando(docs)
        identity.version = self.identify_version(identity, docs)
        if identity.status == "identity_incomplete":
            return BandoBuildResult(False, "identity_incomplete", identity=identity.to_dict(), sources=[d.source_record() for d in docs], missing_documents=_missing_docs(docs), validation={"blocking_issues": identity.missing_fields}, approval_ready=False)
        rules_extraction = self.extract_rules(identity, docs)
        calculations = self.extract_calculations(identity, docs)
        conflicts = self.extract_conflicts(docs, rules_extraction.rules)
        validation = self.validate_draft(identity, docs, rules_extraction, calculations, conflicts)
        path = self.output_root / "drafts" / "bandi" / identity.bando_id / identity.version
        self._write_draft(path, identity, docs, rules_extraction, calculations, conflicts)
        self._upsert_registry(identity, path)
        content_hash = sha256_tree(path)
        return BandoBuildResult(
            True,
            "draft_created" if validation.ok else "incomplete_sources",
            identity.bando_id,
            identity.version,
            str(path),
            content_hash,
            identity.to_dict(),
            [d.source_record() for d in docs],
            rules_extraction.rules,
            calculations.calculations,
            conflicts,
            _missing_docs(docs),
            rules_extraction.uncovered_categories,
            validation.to_dict(),
            validation.ok,
        )

    def update_draft(self, request: BandoBuildRequest | dict[str, Any]) -> BandoBuildResult:
        return self.build_draft(request)

    def validate_draft(self, identity: BandoIdentityProposal, documents: list[BandoDocumentClassification] | None = None, rules: BandoRuleExtraction | None = None, calculations: BandoCalculationExtraction | None = None, conflicts: list[dict[str, Any]] | None = None) -> BandoBuildValidation:
        issues = []
        warnings = []
        documents = documents or []
        rules = rules or BandoRuleExtraction([], CATEGORIES[:])
        conflicts = conflicts or []
        if identity.status == "identity_incomplete":
            issues.extend(identity.missing_fields)
        if not _primary(documents):
            issues.append("primary_source_missing")
        if not rules.rules:
            issues.append("rules_missing")
        if conflicts:
            issues.append("conflicting_official_documents")
        if rules.uncovered_categories:
            warnings.extend(f"uncovered:{cat}" for cat in rules.uncovered_categories)
        return BandoBuildValidation(not issues, issues, warnings)

    def compare_versions(self, bando_id: str, from_version: str, to_version: str, root: str | Path | None = None) -> dict[str, Any]:
        base = Path(root) if root else self.output_root
        left = _load_manifest(base / "drafts" / "bandi" / bando_id / from_version / "domain.yaml")
        right = _load_manifest(base / "drafts" / "bandi" / bando_id / to_version / "domain.yaml")
        if not left or not right:
            return {"status": "missing_version", "bando_id": bando_id}
        if left.get("edition") != right.get("edition"):
            update_type = "new_edition"
        elif from_version != to_version:
            update_type = "new_version"
        elif left.get("rule_set_hash") != right.get("rule_set_hash"):
            update_type = "rule_update"
        else:
            update_type = "document_update" if left.get("source_hash") != right.get("source_hash") else "unchanged"
        return {"status": "ok", "bando_id": bando_id, "from": from_version, "to": to_version, "update_type": update_type}

    def discover_missing_sources(self, bando_id: str, version: str) -> dict[str, Any]:
        manifest = self._load_bando_manifest(bando_id, version)
        if not manifest:
            return {"status": "missing_context", "bando_id": bando_id, "version": version, "missing_documents": []}
        present = {item.get("source_type") for item in manifest.get("official_sources", [])}
        present.update(item.get("source_type") for item in manifest.get("faq", []))
        present.update(item.get("source_type") for item in manifest.get("amendments", []))
        wanted = {
            "official_faq": "FAQ ufficiale",
            "official_amendment": "rettifica ufficiale",
            "official_deadline_extension": "proroga ufficiale",
            "official_post_selection_agreement": "accordo post-selezione",
            "official_reporting_manual": "manuale di rendicontazione",
            "official_attachment": "allegati ufficiali",
            "official_application_form": "formulario ufficiale",
            "official_budget_template": "budget ufficiale",
        }
        missing = [{"document_type": key, "label": label, "status": "not_found"} for key, label in wanted.items() if key not in present]
        return {"status": "ok", "bando_id": bando_id, "version": version, "missing_documents": missing}

    def research_web(self, bando_id: str, version: str, *, allow_web: bool = False, offline: bool = False, provider=None, fetcher: SourceFetcher | None = None) -> dict[str, Any]:
        manifest = self._load_bando_manifest(bando_id, version)
        if not manifest:
            return {"status": "missing_context", "bando_id": bando_id, "version": version}
        missing = self.discover_missing_sources(bando_id, version).get("missing_documents", [])
        request = WebResearchRequest.from_env(
            bando_id=bando_id,
            version=version,
            title=manifest.get("title") or manifest.get("display_name") or "",
            issuer=manifest.get("issuer") or "",
            edition=manifest.get("edition") or "",
            territory=manifest.get("territory") or "",
            official_domain=(infer_official_domains(manifest.get("issuer") or "") or [""])[0],
            missing_documents=[item["document_type"] for item in missing],
            allow_web=allow_web,
            offline=offline,
        )
        result = BandoWebResearcher(provider=provider, fetcher=fetcher).research(request)
        out = result.to_dict()
        out["missing_documents"] = missing
        return out

    def assess_source_candidates(self, candidates: list[dict[str, Any]], *, issuer: str = "") -> dict[str, Any]:
        jury = SourceJury()
        assessments = []
        for row in candidates:
            candidate = SourceCandidate(**row)
            authority = assess_authority(candidate, issuer=issuer)
            assessments.append({"candidate": candidate.to_dict(), "authority": authority.to_dict(), "jury": jury.assess(candidate, authority).to_dict()})
        return {"status": "ok", "assessments": assessments}

    def fetch_approved_sources(self, candidates: list[dict[str, Any]], *, cache_dir: str = ".ralf_run/bando_web_cache") -> dict[str, Any]:
        fetcher = SourceFetcher(cache_dir=cache_dir)
        fetched = [fetcher.fetch(item["url"]).to_dict() for item in candidates if item.get("url")]
        return {"status": "ok", "fetched_sources": fetched}

    def merge_source_sets(self, local_sources: list[dict[str, Any]], web_sources: list[dict[str, Any]]) -> dict[str, Any]:
        jury = SourceJury()
        merged = list(local_sources)
        conflicts = []
        seen = {item.get("checksum") for item in local_sources if item.get("checksum")}
        for web in web_sources:
            checksum = web.get("checksum") or web.get("fetch", {}).get("checksum")
            if checksum and checksum in seen:
                continue
            for local in local_sources:
                conflict = jury.assess_conflict(local, {"checksum": checksum, "version": web.get("version")}).to_dict()
                if conflict["status"] != "same_document":
                    conflicts.append(conflict)
            merged.append(web)
        return {"status": "ok", "sources": merged, "conflicts": conflicts, "validation_required": bool(conflicts or web_sources)}

    def rebuild_with_discovered_sources(self, bando_id: str, version: str, *, allow_web: bool = False, offline: bool = False, provider=None) -> dict[str, Any]:
        result = self.research_web(bando_id, version, allow_web=allow_web, offline=offline, provider=provider)
        if result.get("status") in {"web_disabled", "search_provider_unavailable", "no_candidates", "sources_rejected"}:
            return result
        return {
            "status": "validation_required" if result.get("accepted_sources") else result.get("status", "not_found"),
            "bando_id": bando_id,
            "version": version,
            "new_documents": result.get("new_documents", []),
            "accepted_sources": result.get("accepted_sources", []),
            "human_review_required": True,
            "active_modified": False,
        }

    def _load_bando_manifest(self, bando_id: str, version: str) -> dict[str, Any]:
        path = self.output_root / "drafts" / "bandi" / bando_id / version / "domain.yaml"
        return _load_manifest(path)

    def _inspect_source(self, source: BandoSourceInput) -> BandoDocumentClassification:
        path = Path(source.path)
        text = _extract_text(path)
        title = _extract_title(text) or path.stem.replace("_", " ")
        issuer = _extract_issuer(text)
        source_type = _classify_type(source.role, text)
        binding = "binding_official" if source_type in OFFICIAL_TYPES and source_type not in {"official_attachment"} and not _forbidden_source(text) else "supporting_not_binding"
        if source_type == "official_attachment":
            binding = "binding_official"
        if _forbidden_source(text):
            source_type = "supporting_document"
            binding = "supporting_not_binding"
        source_id = _slug(f"{source_type} {title}")[:80]
        return BandoDocumentClassification(source_id, title, source_type, issuer, str(path), sha256_file(path) if path.is_file() else "", _extract_publication_date(text), "", binding, _sections(text), "", text)

