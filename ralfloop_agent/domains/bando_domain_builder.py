@dataclass
class BandoSourceInput:
    path: str
    role: str = "supporting_documents"
    metadata: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class BandoBuildRequest:
    primary_document: str | None = None
    attachments: list[str] = field(default_factory=list)
    faq_documents: list[str] = field(default_factory=list)
    amendments: list[str] = field(default_factory=list)
    referenced_regulations: list[str] = field(default_factory=list)
    operational_manuals: list[str] = field(default_factory=list)
    supporting_documents: list[str] = field(default_factory=list)
    output_root: str = "domains"
    force: bool = False

    def sources(self) -> list[BandoSourceInput]:
        pairs = []
        if self.primary_document:
            pairs.append(BandoSourceInput(self.primary_document, "primary_document"))
        for attr, role in (
            ("attachments", "attachments"),
            ("faq_documents", "faq_documents"),
            ("amendments", "amendments"),
            ("referenced_regulations", "referenced_regulations"),
            ("operational_manuals", "operational_manuals"),
            ("supporting_documents", "supporting_documents"),
        ):
            for path in getattr(self, attr):
                pairs.append(BandoSourceInput(path, role))
        return pairs


@dataclass
class BandoDocumentClassification:
    source_id: str
    title: str
    source_type: str
    issuer: str
    path: str
    checksum: str
    published_at: str | None = None
    retrieved_at: str = ""
    binding_level: str = "supporting_not_binding"
    sections_used: list[str] = field(default_factory=list)
    notes: str = ""
    text: str = ""

    def source_record(self) -> dict[str, Any]:
        data = asdict(self)
        data.pop("text", None)
        data["reliability"] = 1.0 if self.binding_level == "binding_official" else 0.6
        return data

    def to_dict(self) -> dict[str, Any]:
        return self.source_record() | {"text_length": len(self.text)}


