def _extract_text(path: Path) -> str:
    if not path.exists():
        return ""
    suffix = path.suffix.lower()
    if suffix == ".pdf":
        try:
            proc = subprocess.run(["pdftotext", "-layout", str(path), "-"], check=False, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True, timeout=30)
            if proc.returncode == 0 and proc.stdout.strip():
                return proc.stdout
        except (OSError, subprocess.TimeoutExpired):
            pass
    if suffix == ".docx":
        try:
            with zipfile.ZipFile(path) as archive:
                xml = archive.read("word/document.xml")
            root = ElementTree.fromstring(xml)
            return " ".join(node.text or "" for node in root.iter() if node.text)
        except Exception:
            return ""
    return path.read_text(encoding="utf-8", errors="replace")


def _classify_type(role: str, text: str) -> str:
    low = text.lower()
    if role == "amendments" or "rettifica" in low:
        return "official_amendment"
    if role == "faq_documents" or re.search(r"\bfaq\b|domande frequenti", low):
        return "official_faq"
    if role == "referenced_regulations":
        return "referenced_regulation"
    if role == "operational_manuals" or "manuale" in low:
        return "official_operational_manual"
    if role == "attachments":
        return "official_attachment"
    if role == "primary_document" and "bando" in low:
        return "primary_official_document"
    return "supporting_document"


def _forbidden_source(text: str) -> bool:
    low = text.lower()
    return any(marker in low for marker in FORBIDDEN_SOURCE_MARKERS)


def _primary(documents: list[BandoDocumentClassification]) -> BandoDocumentClassification | None:
    for doc in documents:
        if doc.source_type == "primary_official_document":
            return doc
    for doc in documents:
        if doc.binding_level == "binding_official":
            return doc
    return documents[0] if documents else None


def _extract_title(text: str) -> str:
    lines = [ln.strip(" \t-_–") for ln in text.splitlines() if ln.strip(" \t-_–")]
    for pat in (r"Il Bando\s+([^\n]+?)\s+di\s+Fondazione", r"bando[ \"“]+([^\n”]+)[\"”]", r"^([A-ZÀ-Ú][\wÀ-ÿ' ]{3,80})$"):
        m = re.search(pat, text, re.I | re.M)
        if m:
            return _clean_title(m.group(1))
    return _clean_title(" ".join(lines[:2])) if lines else ""


def _clean_title(value: str) -> str:
    value = re.sub(r"\s+", " ", value.replace("–", "-")).strip(" -.")
    value = re.sub(r"\s*\(.*?di seguito.*$", "", value, flags=re.I)
    value = re.sub(r"\s+di seguito.*$", "", value, flags=re.I)
    return value[:140]


def _extract_issuer(text: str) -> str:
    m = re.search(r"Fondazione\s+[A-ZÀ-Ú][\wÀ-ÿ]+", text)
    return re.sub(r"\s+", " ", m.group(0)).strip() if m else ""


def _extract_edition(text: str) -> str:
    for pat in (r"BANDI\s+(20\d{2})", r"Regolamento\s+(20\d{2})", r"edizione\s+(20\d{2})", r"(20\d{2})"):
        m = re.search(pat, text, re.I)
        if m:
            return m.group(1)
    return ""


def _extract_publication_date(text: str) -> str | None:
    m = re.search(r"(\d{1,2})\s+(gennaio|febbraio|marzo|aprile|maggio|giugno|luglio|agosto|settembre|ottobre|novembre|dicembre)\s+(20\d{2})", text, re.I)
    return _it_date(m) if m else None


def _extract_deadline(text: str) -> str | None:
    if re.search(r"senza\s+scadenza", text, re.I):
        return "no_fixed_deadline"
    deadline_table = re.search(
        r"Scadenza(?P<body>.{0,220}?ore\s*(?P<hour>\d{1,2}))",
        text,
        re.I | re.S,
    )
    if deadline_table:
        dates = list(
            re.finditer(
                r"(\d{1,2})\s+(gennaio|febbraio|marzo|aprile|maggio|giugno|luglio|agosto|settembre|ottobre|novembre|dicembre)\s+(20\d{2})",
                deadline_table.group("body"),
                re.I,
            )
        )
        if dates:
            date = _it_date(dates[-1])
            return f"{date}T{int(deadline_table.group('hour')):02d}:00:00+02:00"
    submission = re.search(
        r"\bal\s+(\d{1,2})\s+(gennaio|febbraio|marzo|aprile|maggio|giugno|luglio|agosto|settembre|ottobre|novembre|dicembre)\s+(20\d{2}).{0,80}?ore\s*(\d{1,2})",
        text,
        re.I | re.S,
    )
    if submission:
        date = _it_date(submission)
        return f"{date}T{int(submission.group(4)):02d}:00:00+02:00"
    matches = list(re.finditer(r"(\d{1,2})\s+(gennaio|febbraio|marzo|aprile|maggio|giugno|luglio|agosto|settembre|ottobre|novembre|dicembre)\s+(20\d{2})(?:[^\n]{0,80}?ore\s*(\d{1,2}))?", text, re.I))
    if not matches:
        return None
    m = matches[-1]
    date = _it_date(m)
    hour = m.group(4)
    return f"{date}T{int(hour):02d}:00:00+02:00" if hour else date


def _it_date(match: re.Match[str]) -> str:
    months = {"gennaio": 1, "febbraio": 2, "marzo": 3, "aprile": 4, "maggio": 5, "giugno": 6, "luglio": 7, "agosto": 8, "settembre": 9, "ottobre": 10, "novembre": 11, "dicembre": 12}
    return f"{match.group(3)}-{months[match.group(2).lower()]:02d}-{int(match.group(1)):02d}"


def _extract_territory(text: str) -> str:
    if re.search(r"Lombardia.*Novara.*Verbano", text, re.I | re.S):
        return "Lombardia; Novara; Verbano-Cusio-Ossola"
    if re.search(r"realizzat[ie]?\s+in\s+Italia|sede legale in Italia", text, re.I):
        return "Italy"
    return ""


def _extract_amount_range(text: str) -> tuple[int | None, int | None]:
    m = re.search(r"(?:compres[ao]|tra|fra)\s+(?:i\s+)?(?:€\s*)?([\d.]{2,})\s*(?:euro)?\s*(?:e|ed|-)\s+(?:i\s+)?(?:€\s*)?([\d.]{2,})", text, re.I)
    if not m:
        anchor = re.search(r"(?:richiesta|contributo)[^.]{0,220}?(?:compres[ao]|tra|fra)", text, re.I)
        if not anchor:
            return None, None
        amounts = re.findall(r"(?:€\s*)?(\d{2,3}(?:\.\d{3})+|\d{5,})", text[anchor.start() : anchor.start() + 360])
        if len(amounts) < 2:
            return None, None
        return _money(amounts[0]), _money(amounts[1])
    return _money(m.group(1)), _money(m.group(2))


def _money(value: str) -> int:
    raw = value.replace(".", "")
    return int(raw)


def _extract_max_rate(text: str) -> float | None:
    m = re.search(r"massimo\s+del\s+(\d{1,3})%|superiore\s+al\s+(\d{1,3})%", text, re.I)
    if not m:
        return None
    return int(m.group(1) or m.group(2)) / 100


def _extract_min_rate(text: str) -> float | None:
    m = re.search(r"inferiore\s+(?:ad\s+almeno\s+)?(?:al\s+)?(\d{1,3})%", text, re.I)
    return int(m.group(1)) / 100 if m else None


def _extract_duration(text: str) -> dict[str, Any] | None:
    m = re.search(r"durata[^.]{0,80}?compresa\s+tra\s+(\d+)\s+e\s+(\d+)\s+mesi", text, re.I)
    if m:
        return {"min_months": int(m.group(1)), "max_months": int(m.group(2))}
    m = re.search(r"durata[^.]{0,160}?(\d+)\s+e\s+(\d+)\s+mesi", text, re.I)
    if m:
        return {"min_months": int(m.group(1)), "max_months": int(m.group(2))}
    m = re.search(r"durata\s+massima\s+di\s+(\d+)\s+mesi", text, re.I)
    if m:
        return {"max_months": int(m.group(1))}
    return None


def _extract_eligible_subjects(text: str) -> list[str]:
    if re.search(r"organizzazioni\s+non\s+profit", text, re.I):
        return ["organizzazioni non profit"]
    bullets = re.findall(r"•\s+([^\n]{5,80})", text)
    return [b.strip(" .;") for b in bullets[:8] if re.search(r"associazioni|enti|cooperative|imprese", b, re.I)]


def _extract_required_documents(text: str) -> list[str]:
    docs = []
    for key, label in (("budget", "budget"), ("quadro logico", "logical_framework"), ("statuto", "statute"), ("accordo", "partnership_agreement"), ("lettere di adesione", "support_letters"), ("dichiarazione", "declaration")):
        if re.search(key, text, re.I):
            docs.append(label)
    return sorted(set(docs))


def _extract_scoring(text: str) -> list[str]:
    keys = []
    for token in ("coerenza", "qualità", "impatto", "innovazione", "rete", "sostenibilità", "monitoraggio"):
        if token in text.lower():
            keys.append(token)
    return keys


def _extract_exclusions(text: str) -> list[str]:
    out = []
    if re.search(r"mera\s+ricerca", text, re.I):
        out.append("mere_research")
    if re.search(r"grandi\s+eventi\s+episodici", text, re.I):
        out.append("large_episodic_events")
    if re.search(r"esclusivamente\s+in\s+ambito\s+scolastico", text, re.I):
        out.append("school_only_children_activities")
    if re.search(r"attività\s+formative\s+rivolte\s+agli\s+operatori", text, re.I):
        out.append("operator_training_only")
    if re.search(r"oltre\s+tale\s+limite", text, re.I):
        out.append("late_or_wrong_modality_submission")
    return out


